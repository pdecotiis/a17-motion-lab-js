// The version as GSAP code, written to be read: the way a developer would write it by hand, top to bottom, with plain names and no helpers of its own.
//   1. the easing tokens (CustomEase), and the entrance presets the version uses (a small table of fade and move);
//   2. the entrance: one timeline, a comment for each part, `from` (the end is where the element already is) wherever that is true;
//   3. the states: what each part looks like (only where it differs from the rest), one `show()` function that tweens to a state, and the triggers as plain
//      event listeners.
// GSAP has no springs, so this is easing only.

/** The same options as the other formats; GSAP code has everything it uses in the one file, so the preset options do nothing. */
export interface GsapCodeOptions { component?: string; includePresets?: boolean; presetsPath?: string }

const NATURAL = new Set(['opacity:1', 'x:0', 'y:0', 'xPercent:0', 'yPercent:0', 'scale:1', 'scaleX:1', 'scaleY:1', 'rotation:0']);

export function buildGsapCode(version: MotionVersion, raw: Record<string, unknown>, options: GsapCodeOptions = {}): string {
  const { component = 'component' } = options;
  const ease = new EaseRegistry(raw);
  const names = new Set<string>(['el']);
  const nameFor = (layer: string): string => {   // a plain variable name for a layer's elements
    let n = camel(layer);
    if (names.has(n)) n += 'Layer';
    names.add(n);
    return n;
  };
  const targets = new Map<string, string>();   // layer -> variable
  const targetOf = (layer: string | null): string => {
    if (layer === null) return 'el';
    if (!targets.has(layer)) targets.set(layer, nameFor(layer));
    return targets.get(layer)!;
  };

  const entrance = version.model !== undefined || version.entrance !== undefined ? entranceLines(version, raw, ease, targetOf) : { lines: [], presets: [] as string[], scroll: false };
  const states = version.interaction ? stateLines(version, raw, ease) : { lines: [] as string[] };

  const tokens = getTokenRefs(version, raw).tokens.filter(t => !t.startsWith('bounce.'));
  const trigger = describeTrigger(version.trigger);
  const out: string[] = [
    `// ${component} ${version.id}: ${version.label}`,
    trigger ? `// Plays: ${trigger}` : '// Plays: trigger not specified, confirm with the designer',
    '// Generated by Motion Lab from the same version file as motion.css. GSAP has no springs, so this is easing only.',
    `// Tokens: ${tokens.length ? tokens.join(', ') : 'none'}`,
    '',
    `gsap.registerPlugin(CustomEase${entrance.scroll ? ', ScrollTrigger' : ''});`,
    '',
    '// easing tokens',
    ...[...ease.entries].map(([n, e]) => `CustomEase.create(${str(n)}, ${str(e.bezier.replace(/, /g, ','))});`),
    '',
    ...(entrance.presets.length ? [
      '// entrance presets (the project\'s shared sheet): fade = opacity, move = translateY and scale',
      'const presets = {', ...entrance.presets, '};', '',
    ] : []),
    `const el = document.querySelector(${str(`.${component}`)});`,
    ...[...targets].map(([layer, variable]) => `const ${variable} = el.querySelectorAll(${str(`[data-motion="${layer}"]`)});`),
    '',
    ...entrance.lines,
    ...(entrance.lines.length && states.lines.length ? [''] : []),
    ...states.lines,
  ];
  return out.join('\n').replace(/\n+$/, '') + '\n';
}

// ── The entrance ───────────────────────────────────────────────────────────

function entranceLines(
  version: MotionVersion, raw: Record<string, unknown>, ease: EaseRegistry, targetOf: (layer: string | null) => string,
): { lines: string[]; presets: string[]; scroll: boolean } {
  const steps = stepsOf(version);
  const policy = getReducedMotionPolicy(version);
  const trigger = version.trigger;
  const inView = trigger?.on === 'in-view';
  const timeline = inView
    ? `gsap.timeline({ scrollTrigger: { trigger: el, start: ${str(`top ${Math.round((1 - (trigger.threshold ?? 0)) * 100)}%`)}, ${trigger.once === false ? 'toggleActions: "play none none reset"' : 'once: true'} } })`
    : 'gsap.timeline()';

  // the presets the version uses, as a table (the same sheet as the Presets view)
  const used = [...new Set(steps.flatMap(e => (e.preset ? [e.preset] : [])))];
  const presets = used.map(name => {
    const tracks = presetTracks(name);
    const move = tracks.find(t => t.track !== 'fade')!, fade = tracks.find(t => t.track === 'fade') ?? move;
    const p = presetOf(name);
    const timing = (m: { duration: string; easing: string }): string => `duration: ${seconds(parseMs(m.duration, raw))}, ease: ${str(ease.nameOf(m.easing))}`;
    const rise = parseFloat(String(raw[p.rise]));
    const scale = p.scale ? Number(raw[p.scale]) : undefined;
    return `  ${name}: {\n    fade: { opacity: 0, ${timing(fade.model)} },\n    move: { y: ${num(rise)}, ${scale !== undefined ? `scale: ${num(scale)}, ` : ''}${timing(move.model)} },\n  },`;
  });

  const body: string[] = [], reduced: string[] = [];
  const done = new Set<string>();
  steps.forEach((entry: StepEntry) => {
    const { name, version: step } = entry;
    const target = targetOf(name);
    const at = seconds(parseMs(step.model.delay, raw));
    if (entry.preset) {
      const key = `${name}:${entry.preset}`;
      const gap = entry.elementStagger ? `, stagger: ${seconds(parseMs(entry.elementStagger, raw))}` : '';
      const props = (track: 'fade' | 'move'): string => `{ ...presets.${entry.preset}.${track}${gap} }`;
      if (entry.track === 'fade' || entry.track === undefined) body.push(`  tl.from(${target}, ${props('fade')}, ${at});`);
      if (entry.track !== 'fade') body.push(`  tl.from(${target}, ${props('move')}, ${at});`);
      if (!done.has(key) && (entry.track === 'fade' || entry.track === undefined)) {
        done.add(key);
        reduced.push(`  tl.from(${target}, { ...presets.${entry.preset}.fade${gap}, duration: ${seconds(Math.min(parseMs(String(presetTracks(entry.preset).find(t => t.track === 'fade')?.model.duration ?? presetTracks(entry.preset)[0]!.model.duration), raw), REDUCED_MOTION_FADE_MS))} }, ${at});`);
      }
      return;
    }
    const p = playbackOf(step, raw);
    const frames = orderedKeyframes(p.keyframes);
    const converted = frames.map(f => gsapProps(f.kf));
    const easing = str(ease.nameOf(step.model.easing));
    const label = `  // ${name ?? 'the component'}`;
    const first = converted[0]!.props, last = converted[converted.length - 1]!.props;
    if (frames.length === 2 && last.every(([k, v]) => NATURAL.has(`${k}:${v}`))) {
      body.push(label, `  tl.from(${target}, ${obj(first, [['duration', seconds(p.pairedMs)], ['ease', easing]])}, ${at});`);
    } else if (frames.length === 2) {
      body.push(label, `  tl.fromTo(${target}, ${obj(first)}, ${obj(last, [['duration', seconds(p.pairedMs)], ['ease', easing]])}, ${at});`);
    } else {
      const kfs = frames.map((f, i) => `${str(`${Math.round(f.offset * 100)}%`)}: ${obj(converted[i]!.props)}`).join(', ');
      body.push(label, `  tl.to(${target}, { keyframes: { ${kfs}, easeEach: ${easing} }, duration: ${seconds(p.pairedMs)} }, ${at});`);
    }
    for (const c of converted) for (const u of c.unsupported) body.push(`  // Not converted (GSAP wants x, y, scale, rotation): ${u}`);
    const rp = playbackOf(step, raw, { reducedMotion: true });
    if (rp.keyframes.some(k => 'opacity' in k)) {
      reduced.push(`  tl.from(${target}, { opacity: ${rp.keyframes[0]!.opacity}, duration: ${seconds(Math.min(rp.pairedMs, REDUCED_MOTION_FADE_MS))}, ease: ${easing} }, ${at});`);
    }
  });

  const lines: string[] = [
    '// entrance',
    ...(version.stagger ? [`// On a page, each section starts ${seconds(parseMs(version.stagger, raw))}s after the one before (${version.stagger in raw ? version.stagger : 'hard-coded, not a token'}): delay this timeline by index * ${seconds(parseMs(version.stagger, raw))}.`] : []),
    'const mm = gsap.matchMedia();',
    '',
    'mm.add("(prefers-reduced-motion: no-preference)", () => {',
    `  const tl = ${timeline};`,
    '',
    ...body,
    '});',
    ...(policy === 'none' || reduced.length === 0 ? [
      '', '// reduced motion: no animation, the element shows its end state',
    ] : [
      '', `// reduced motion: the same fades (at most ${REDUCED_MOTION_FADE_MS}ms), no movement`,
      'mm.add("(prefers-reduced-motion: reduce)", () => {', `  const tl = ${timeline};`, '', ...reduced, '});',
    ]),
  ];
  return { lines, presets, scroll: inView };
}

// ── The states ─────────────────────────────────────────────────────────────

const gsapName = (k: string): string => (k === 'rotate' ? 'rotation' : k);
const look = (values: Record<string, string | number>): string =>
  `{ ${Object.entries(values).map(([k, v]) => `${gsapName(k)}: ${typeof v === 'number' ? num(v) : str(v)}`).join(', ')} }`;
const key = (n: string): string => (/^[a-zA-Z_]\w*$/.test(n) ? n : str(n));
/** The most common value in a list (by what it says), and what it was. */
function commonOf<T>(items: T[]): T {
  const counts = new Map<string, { item: T; n: number }>();
  for (const item of items) { const k = JSON.stringify(item); counts.set(k, { item, n: (counts.get(k)?.n ?? 0) + 1 }); }
  return [...counts.values()].sort((a, b) => b.n - a.n)[0]!.item;
}

function stateLines(version: MotionVersion, raw: Record<string, unknown>, ease: EaseRegistry): { lines: string[] } {
  const i = version.interaction!;
  const states = stateNames(i);
  const parts = interactionParts(i).filter(part => partProps(i, part).length > 0);
  const partKey = (part: string | null): string => part ?? 'root';

  // what each part looks like in each state; the rest is what it looks like most often, so a state only says what is different
  const looks = new Map(parts.map(part => [part, motionStates(i, raw, part)]));
  const rest = new Map(parts.map(part => [part, commonOf(states.map(s => looks.get(part)![s]!))]));
  const different = (part: string | null, state: string): boolean => JSON.stringify(looks.get(part)![state]) !== JSON.stringify(rest.get(part));

  // how long it takes to go to each state: most parts take the same, and the others are listed
  const timingOf = (part: string | null, state: string): string => {
    const t = timingFor(i, part, state);
    const delay = parseMs(t.delay, raw);
    return `duration: ${seconds(parseMs(t.duration, raw))}, ease: ${str(ease.nameOf(t.easing))}${delay ? `, delay: ${seconds(delay)}` : ''}`;
  };
  const timing = new Map(states.map(s => [s, commonOf(parts.map(part => timingOf(part, s)))]));
  const exceptions = states.flatMap(s => parts.filter(part => timingOf(part, s) !== timing.get(s)).map(part => ({ s, part })));

  const reducedFade = parts.some(part => partProps(i, part).includes('opacity')) && getReducedMotionPolicy(version) === 'fade';
  const hasProject = (i.triggers ?? []).some(t => !isCoreTrigger(t));
  const lines: string[] = [
    '// states',
    '// what each part looks like when no state says otherwise',
    'const rest = {',
    ...parts.map(part => `  ${key(partKey(part))}: ${look(rest.get(part)!)},`),
    '};',
    '',
    '// the states: only the parts that look different from the rest',
    'const states = {',
    ...states.flatMap(s => [
      `  ${key(s)}: {${s === i.initial ? ' // where it starts' : ''}`,
      ...parts.filter(part => different(part, s)).map(part => `    ${key(partKey(part))}: ${look(looks.get(part)![s]!)},`),
      '  },',
    ]),
    '};',
    '',
    '// how long it takes to go to each state',
    'const timing = {',
    ...states.map(s => `  ${key(s)}: { ${timing.get(s)} },`),
    '};',
    ...(exceptions.length ? [
      '',
      '// the parts that take a different time',
      'const differently = {',
      ...states.filter(s => exceptions.some(e => e.s === s)).flatMap(s => [
        `  ${key(s)}: {`, ...exceptions.filter(e => e.s === s).map(e => `    ${key(partKey(e.part))}: { ${timingOf(e.part, s)} },`), '  },',
      ]),
      '};',
    ] : []),
    '',
    `let current = ${str(i.initial)};`,
    ...(hasProject ? ['const afterShow = []; // functions to run after every move (a project trigger below adds one)'] : []),
    'const reduced = window.matchMedia("(prefers-reduced-motion: reduce)");',
    'const partsOf = part => (part === "root" ? [el] : el.querySelectorAll(`[data-motion=${part}]`));',
    '',
    '// go to a state, from wherever the parts are now (a move cut short carries on from where it was)',
    'function show(state) {',
    '  current = state;',
    '  el.dataset.state = state;',
    '  for (const part of Object.keys(rest)) {',
    exceptions.length ? '    const move = { ...timing[state], ...differently[state]?.[part] };' : '    const move = timing[state];',
    ...(reducedFade
      ? [`    // reduced motion: an opacity change still fades (at most ${REDUCED_MOTION_FADE_MS}ms), movement snaps`,
        '    const props = { ...rest[part], ...states[state][part] };',
        '    if (reduced.matches) { const { opacity, ...movement } = props; gsap.set(partsOf(part), movement); if (opacity !== undefined) gsap.to(partsOf(part), { opacity, duration: Math.min(move.duration, ' + seconds(REDUCED_MOTION_FADE_MS) + '), overwrite: "auto" }); continue; }',
        '    gsap.to(partsOf(part), { ...props, ...move, overwrite: "auto" });']
      : ['    // reduced motion: no animation, it goes straight to the state',
        '    gsap.to(partsOf(part), { ...rest[part], ...states[state][part], ...move, duration: reduced.matches ? 0 : move.duration, overwrite: "auto" });']),
    '  }',
    ...(hasProject ? ['  afterShow.forEach(fn => fn());'] : []),
    '}',
    '',
    '// start in the first state',
    'el.dataset.state = current;',
    'for (const part of Object.keys(rest)) gsap.set(partsOf(part), { ...rest[part], ...states[current][part] });',
    '',
    ...triggerLines(version),
  ];
  return { lines };
}

// ── The triggers, as plain event listeners ─────────────────────────────────

function triggerLines(version: MotionVersion): string[] {
  const i = version.interaction!;
  const triggers = i.triggers ?? [];
  if (triggers.length === 0) return ['// No triggers are declared for this version: call show(state) from whatever starts the change.'];
  const where = (target?: string): string => (target ? `el.querySelector(${str(`[data-motion="${target}"]`)})` : 'el');
  const out: string[] = ['// triggers'];
  const needsNext = triggers.some(t => !isCoreTrigger(t) || ('toggle' in t && t.toggle));
  if (needsNext) out.push('const next = list => list[(list.indexOf(current) + 1) % list.length];', '');
  const hoverOf = (target?: string): string | undefined => {
    const hover = triggers.find(t => t.on === 'hover' && t.target === target);
    const state = (hover as { state?: unknown } | undefined)?.state;
    return typeof state === 'string' ? state : undefined;
  };
  for (const t of triggers) {
    if (!isCoreTrigger(t)) {
      const project = getTrigger(t.on);
      const settings = project?.exportSettings ? project.exportSettings(t, {}) : t;
      out.push(`// ${t.on}`, '{', `  const t = ${JSON.stringify(settings)};`, ...(project?.exportCode ? project.exportCode(t).map(l => `  ${l}`) : [`  // "${t.on}" is a project trigger with no export code: wire it by hand, its settings are in t`]), '}', '');
      continue;
    }
    const target = where(t.target);
    if (t.on === 'click' && 'set' in t) out.push('// click', `${target}.addEventListener("click", () => show(${str(t.set)}));`, '');
    else if (t.on === 'click') out.push(`// click: ${t.toggle.join(', ')}`, `${target}.addEventListener("click", () => show(next(${JSON.stringify(t.toggle)})));`, '');
    else if (t.on === 'hover') out.push('// hover (a touch never hovers)', `${target}.addEventListener("pointerenter", e => { if (e.pointerType !== "touch") show(${str(t.state)}); });`, `${target}.addEventListener("pointerleave", () => show(${str(i.initial)}));`, '');
    else if (t.on === 'press') {
      const back = hoverOf(t.target) ?? i.initial;
      out.push('// press: held down, then back to where it was', `${target}.addEventListener("pointerdown", e => { if (e.button === 0) show(${str(t.state)}); });`, `document.addEventListener("pointerup", () => { if (current === ${str(t.state)}) show(${str(back)}); });`, '');
    } else if (t.on === 'focus') out.push('// focus: by the keyboard', `${target}.addEventListener("focusin", e => { if (e.target.matches(":focus-visible")) show(${str(t.state)}); });`, `${target}.addEventListener("focusout", () => show(${str(i.initial)}));`, '');
    else if (t.on === 'arrows') {
      out.push(`// arrow keys: ${t.states.join(', ')}, left to right, stopping at the ends`, `const order = ${JSON.stringify(t.states)};`,
        'document.addEventListener("keydown", e => {', '  if (e.altKey || e.ctrlKey || e.metaKey || e.shiftKey || e.target.closest("input, textarea, select, [contenteditable]")) return;',
        '  const at = order.indexOf(current);', '  if (e.key === "ArrowRight" && at < order.length - 1) show(order[at + 1]);', '  if (e.key === "ArrowLeft" && at > 0) show(order[at - 1]);', '});', '');
    }
  }
  return out[out.length - 1] === '' ? out.slice(0, -1) : out;
}
