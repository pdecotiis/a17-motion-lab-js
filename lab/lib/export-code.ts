// The same version as code for the library a project uses. The CSS export (css-output.ts) is the
// baseline; these are the same motion in GSAP and Motion terms, built from the same version file and
// the same tokens, so the three cannot drift apart.
//   gsap    easing only (GSAP has no springs): seconds, CustomEase for the easing, a timeline.
//   motion  springs only (as in the lab under Motion): visualDuration, bounce, delay.

export type ExportFormat = 'css' | 'gsap' | 'motion';
export const EXPORT_FORMATS: readonly ExportFormat[] = ['css', 'gsap', 'motion'];
export const EXPORT_LABELS: Record<ExportFormat, string> = { css: 'CSS', gsap: 'GSAP', motion: 'Motion' };
// The file each format is written to by `npm run spec`.
export const EXPORT_FILES: Record<ExportFormat, string> = { css: 'motion.css', gsap: 'motion.gsap.js', motion: 'motion.motion.js' };

// The shared preset definitions, one file per format. They belong to the project, not to a version: npm run spec
// writes them once, to <out>/presets/, and a version's code imports them from there (`presetsPath`).
// GSAP has none: its code carries the presets it uses in the one file.
export const PRESET_FILES: Record<'css' | 'motion', string> = { css: PRESETS_CSS_FILE, motion: 'presets.motion.js' };

export interface ExportCodeOptions {
  component?: string;
  /** Put the shared preset definitions above the component's code (the Generated code panel does; the spec writes them to a file). */
  includePresets?: boolean;
  /** Motion only: the global bounce token for motions that name none. */
  globalBounce?: string;
  /** Where the code imports the shared preset files from, with a trailing slash (default: the same folder). */
  presetsPath?: string;
}

function header(version: MotionVersion, component: string, what: string): string[] {
  const trigger = describeTrigger(version.trigger);
  return [
    `// ${component} ${version.id}: ${version.label}`,
    trigger ? `// Plays: ${trigger}. Call the function when the trigger fires.` : '// Plays: trigger not specified, confirm with the designer. Call the function when it should play.',
    `// Generated by Motion Lab from the same version file as motion.css. ${what}`,
  ];
}

function tokenComment(version: MotionVersion, raw: Record<string, unknown>, format: 'gsap' | 'motion'): string {
  // GSAP plays easings (no bounce); Motion plays springs (no easing).
  const used = getTokenRefs(version, raw).tokens.filter(t => !t.startsWith(format === 'motion' ? 'easing.' : 'bounce.'));
  return used.length ? `// Tokens: ${used.join(', ')}` : '// Tokens: none';
}

