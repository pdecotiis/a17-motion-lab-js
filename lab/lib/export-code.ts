// The version as Motion code (motion.dev): every motion a spring, built from the same arguments the
// lab plays under Motion.
export function buildMotionCode(version: MotionVersion, raw: Record<string, unknown>, options: ExportCodeOptions = {}): string {
  const code = motionCode(version, raw, { ...options, includePresets: false });
  if (!options.includePresets || presetsUsed(stepsOf(version)).length === 0) return code;
  return withSharedPresets(code, buildPresetsMotion(raw, options.globalBounce ?? DEFAULT_BOUNCE), /^import \{ playPreset \}/);
}

function motionCode(version: MotionVersion, raw: Record<string, unknown>, options: ExportCodeOptions): string {
  const { component = 'component', globalBounce = DEFAULT_BOUNCE } = options;
  if (version.interaction) {
    const states = buildMotionInteraction(version, raw, component, globalBounce);
    if (!hasEntrance(version)) return states;
    const { interaction: _i, ...entranceOnly } = version;
    return mergeEntranceAndStates(motionCode(entranceOnly, raw, options), states, version, raw, 'motion', component);
  }
  const fn = `play${pascal(component)}${pascal(version.id)}`;
  const steps = stepsOf(version);
  const staggerMs = version.stagger ? parseMs(version.stagger, raw) : 0;
  const reducedPolicy = getReducedMotionPolicy(version);

  const call = (target: string, step: EntranceVersion, reducedMotion: boolean, indent: string): string[] => {
    const a = motionArgsOf(step, raw, { reducedMotion, globalBounce });
    const o = a.options;
    const delay = o.delay ? `${num(o.delay)} + ` : '';
    const comment = reducedMotion ? '' : [a.bounceToken ?? '', a.note ?? ''].filter(Boolean).join('; ');
    return [
      ...(comment ? [`${indent}// ${comment}`] : []),
      `${indent}controls.push(animate(${target}, ${JSON.stringify(a.keyframes)}, { type: "spring", visualDuration: ${num(o.visualDuration)}, bounce: ${num(o.bounce)}, delay: ${version.stagger ? `${delay}index * stagger` : num(o.delay)} }));`,
    ];
  };

  const targetOf = (name: string | null): string => (name ? `el.querySelectorAll(${str(`[data-motion="${name}"]`)})` : 'el');
  const presetLines = presetCallLines(steps, raw, 'motion', Boolean(version.stagger));
  const plain = steps.filter(e => !e.preset);
  const body = plain.flatMap(({ name, version: step }) => call(targetOf(name), step, false, '  '));
  const reduced = plain
    .filter(({ version: step }) => playbackOf(step, raw, { reducedMotion: true }).keyframes.some(k => 'opacity' in k))
    .flatMap(({ name, version: step }) => call(targetOf(name), step, true, '    '));

  const out: string[] = [
    ...header(version, component, 'Motion plays every motion as a spring.'),
    tokenComment(version, raw, 'motion'),
    `// Bounce: a spring version's own bounce token, otherwise the global bounce setting (${globalBounce}).`,
    '',
    'import { animate } from "motion";',
    ...(presetLines.length ? ['import { playPreset } from "./presets.motion.js";'] : []),
    '',
    `/** Play on \`el\`, the element marked data-motion-target.${version.stagger ? ' `index` staggers siblings: 0, 1, 2…' : ''} Returns the animation controls. */`,
    `export function ${fn}(el, { index = 0 } = {}) {`,
    ...(version.stagger ? [`  const stagger = ${seconds(staggerMs)}; // ${version.stagger in raw ? version.stagger : 'hard-coded, not a token'}`] : []),
    '  const controls = [];',
    '',
    ...(presetLines.length ? ['  // Presets (presets.motion.js): they play only the opacity fade under reduced motion.', ...presetLines, ''] : []),
    ...(plain.length ? [
      '  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {',
      reducedPolicy === 'none' || reduced.length === 0
        ? '    return controls; // reduced motion: no animation, the element shows its end state'
        : `    // reduced motion: an opacity fade of at most ${REDUCED_MOTION_FADE_MS}ms, no movement, no bounce\n${reduced.join('\n')}\n    return controls;`,
      '  }',
      '',
      ...body,
      '',
    ] : []),
    '  return controls;',
    '}',
    '',
  ];
  return out.join('\n');
}

// The version as code in a format: CSS from css-output.ts, GSAP or Motion from here.
export function buildExportCode(
  format: ExportFormat,
  version: MotionVersion,
  raw: Record<string, unknown>,
  options: ExportCodeOptions & { css: string },
): string {
  if (format === 'gsap') return buildGsapCode(version, raw, options);
  if (format === 'motion') return buildMotionCode(version, raw, options);
  return options.css;
}
