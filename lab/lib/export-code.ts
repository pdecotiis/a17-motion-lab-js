const px = (raw: Record<string, unknown>, token: string): number => parseFloat(String(raw[token]));
const tokensOf = (name: string): string => {
  const p = presetOf(name);
  return [p.rise, p.scale, p.move.duration, p.move.easing, ...(p.fade ? [p.fade.duration, p.fade.easing] : [])].filter(Boolean).join(', ');
};

// presets.motion.js: the same table for Motion: every preset a spring. The fade has no bounce (opacity never
// overshoots) unless the preset has no fade timing, when it shares the move's; the move uses `bounce`.
export function buildPresetsMotion(raw: Record<string, unknown>, globalBounce = DEFAULT_BOUNCE): string {
  const bounce = Number(raw[globalBounce] ?? 0.25);
  const rows = PRESET_NAMES.map(name => {
    const tracks = presetTracks(name);
    const move = tracks.find(t => t.track !== 'fade')!;
    const fade = tracks.find(t => t.track === 'fade');
    const p = presetOf(name);
    return `  ${name}: { rise: ${num(px(raw, p.rise))}, ${p.scale ? `scale: ${num(Number(raw[p.scale]))}, ` : ''}move: { duration: ${seconds(parseMs(move.model.duration, raw))} }${fade ? `, fade: { duration: ${seconds(parseMs(fade.model.duration, raw))} }` : ''} }, // ${tokensOf(name).split(', ').filter(t => !t.startsWith('easing.')).join(', ')}`;
  });
  return [
    '// Entrance presets: named, standard entrances (see the Presets view in Motion Lab). Shared by every component that uses one.',
    '// Generated by Motion Lab from the same tokens as presets.css. Motion plays every motion as a spring.',
    `// Bounce: the global bounce setting (${globalBounce}) for the move; the fade has none.`,
    '',
    'import { animate, stagger as staggerDelay } from "motion";',
    '',
    'const presets = {',
    ...rows,
    '};',
    '',
    `const bounce = ${num(bounce)}; // ${globalBounce}`,
    '',
    '/**',
    ' * Play a preset on `target` (an element, or several). `delay` is when it starts and `stagger` the gap between',
    ' * several elements, both in seconds. Returns the animation controls.',
    ' */',
    'export function playPreset(target, name, { delay = 0, stagger = 0 } = {}) {',
    '  const p = presets[name];',
    '  const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;',
    '  const at = stagger ? staggerDelay(stagger, { startDelay: delay }) : delay;',
    '  const fade = p.fade ?? p.move;',
    '  // reduced motion: only the opacity fade, at most 150ms, no bounce; no movement',
    '  const controls = [animate(target, { opacity: [0, 1] }, { type: "spring", visualDuration: reduced ? Math.min(fade.duration, 0.15) : fade.duration, bounce: p.fade || reduced ? 0 : bounce, delay: at })];',
    '  if (!reduced) {',
    '    controls.push(animate(target, { y: [p.rise, 0], ...(p.scale ? { scale: [p.scale, 1] } : {}) }, { type: "spring", visualDuration: p.move.duration, bounce, delay: at }));',
    '  }',
    '  return controls;',
    '}',
    '',
  ].join('\n');
}

// The preset calls of a version: one per element, however many tracks the preset has.
function presetCallLines(entries: StepEntry[], raw: Record<string, unknown>, format: 'gsap' | 'motion', pageStagger: boolean): string[] {
  const seen = new Set<string | null>();
  const out: string[] = [];
  for (const e of entries) {
    if (!e.preset || seen.has(e.name)) continue;
    seen.add(e.name);
    const target = e.name ? `el.querySelectorAll(${str(`[data-motion="${e.name}"]`)})` : 'el';
    const delay = parseMs(e.version.model.delay, raw);
    const gap = e.elementStagger ? parseMs(e.elementStagger, raw) : 0;
    const opts = `{ delay: ${seconds(delay)}${format === 'motion' && pageStagger ? ' + index * stagger' : ''}${gap ? `, stagger: ${seconds(gap)}` : ''} }`;
    out.push(format === 'gsap'
      ? `  tl.add(playPreset(${target}, ${str(e.preset)}, ${opts}), 0);`
      : `  controls.push(...playPreset(${target}, ${str(e.preset)}, ${opts}));`);
  }
  return out;
}

// The shared definitions above the component's code (for the Generated code panel): the component's own
// imports and plugin setup are already in the shared part.
function withSharedPresets(component: string, shared: string, importLine: RegExp): string {
  const own = component.split('\n').filter(l => !importLine.test(l) && !l.startsWith('import ') && !l.startsWith('gsap.registerPlugin('));
  return `${shared}\n// ── The component ──────────────────────────────────────────────────────────\n${own.join('\n').replace(/^\n+/, '')}`;
}

// A version with an entrance and states is the entrance's code (play…) followed by the states' (setup…, goTo…,
// attach…): the entrance first, then call attach once it has finished. They share one file, one import and one
// set of easings; the states' code starts at its `const parts` line.
function mergeEntranceAndStates(entrance: string, states: string, version: MotionVersion, raw: Record<string, unknown>, format: 'gsap' | 'motion', component: string): string {
  const base = `${pascal(component)}${pascal(version.id)}`;
  const lines = states.split('\n');
  const at = lines.findIndex(l => l.startsWith('const parts = ['));
  const head = lines.slice(0, at);
  const body = lines.slice(at);
  const out = entrance.split('\n').map(l => (l.startsWith('// Tokens:') ? tokenComment(version, raw, format) : l));
  // Easings the states use that the entrance did not register.
  const missing = head.filter(l => l.startsWith('CustomEase.create(') && !out.includes(l));
  if (missing.length) {
    const lastEase = out.map(l => l.startsWith('CustomEase.create(') || l.startsWith('gsap.registerPlugin(')).lastIndexOf(true);
    out.splice(lastEase + 1, 0, ...missing);
  }
  const wait = format === 'gsap' ? `play${base}(el).then(() => attach${base}(el))` : `Promise.all(play${base}(el)).then(() => attach${base}(el))`;
  const hint = `// Then ${(version.interaction?.triggers ?? []).length ? `wire its states once the entrance has finished: ${wait}` : `move between states with goTo${base}(el, state)`}.`;
  const first = out.findIndex(l => l.startsWith('// Generated by Motion Lab'));
  out.splice(first + 1, 0, hint);
  const trimmed = out.join('\n').replace(/\n+$/, '\n');
  return `${trimmed}\n// ── States ─────────────────────────────────────────────────────────────────\n\n${body.join('\n')}`;
}

