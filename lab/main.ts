// ── Tokens view ────────────────────────────────────────────────────────────

// The kinds shown as tabs, in this order.
// Bounce only shows under Motion, the one runtime that plays it.
const TOKEN_KINDS = ['duration', 'easing', 'distance', 'scale', 'opacity', 'delay'];
const tokenKinds = (): string[] => (runtime === 'motion' ? [...TOKEN_KINDS, 'bounce'] : TOKEN_KINDS);
// Easings in system order: productive, then expressive, then linear.
const EASING_ORDER = [
  'productive-standard', 'productive-entrance', 'productive-exit',
  'expressive-standard', 'expressive-entrance', 'expressive-exit',
  'linear',
];
// How long an easing preview plays.
const PREVIEW_MS = 600;

function renderTokensView(): void {
  const main = document.getElementById('main-content')!;
  main.innerHTML = '';
  main.className = 'lab-main lab-main--tokens';

  let activeKind = tokenKinds()[0]!;

  const numeric = (value: unknown): number => (typeof value === 'number' ? value : parseFloat(String(value)));

  // A kind's tokens, smallest to largest (easings in system order).
  function tokensOf(kind: string): { key: string; value: unknown }[] {
    const rows = Object.entries(raw)
      .filter(([key]) => key.startsWith(`${kind}.`))
      .map(([key, value]) => ({ key, value }));
    if (kind === 'easing') {
      const rank = (key: string): number => {
        const i = EASING_ORDER.indexOf(tokenLabel(key));
        return i === -1 ? EASING_ORDER.length : i;
      };
      return rows.sort((x, y) => rank(x.key) - rank(y.key));
    }
    return rows.sort((x, y) => numeric(x.value) - numeric(y.value));
  }

  const valueText = (v: unknown): string => (Array.isArray(v) ? `cubic-bezier(${v.join(', ')})` : String(v));

  // What hovering a row says: notes, status, value, usage and old names.
  function tooltipFor(key: string): string {
    const m = meta[key];
    const lines = [key];
    if (m?.description) lines.push(m.description);
    if (m) lines.push(`Status: ${m.status}`);
    lines.push(`Value: ${valueText(raw[key])}`);
    const used = [
      ...(usageIndex.get(key) ?? []).map(u => `${u.componentName}/${u.versionId}`),
      ...(pageUsageIndex.get(key) ?? []).map(p => `page: ${p}`),
    ];
    if (key === globalBounce && runtime === 'motion') used.push('the global bounce setting');
    if (key === defaultStagger) used.push('the default page stagger');
    lines.push(used.length ? `Used by: ${used.join(', ')}` : 'Not used yet');
    if (m?.oldNames?.length) lines.push(`Old names: ${m.oldNames.join(', ')}`);
    return lines.join('\n');
  }

  // The curve for an easing.
  function curveFor(kind: string, _key: string, value: unknown): Curve | null {
    if (kind === 'bounce' && typeof value === 'number') return springCurve(value, PREVIEW_MS);
    return kind === 'easing' && Array.isArray(value) && value.length === 4
      ? { ...bezierCurve(value as [number, number, number, number]), durationMs: PREVIEW_MS }
      : null;
  }

  // Bar preview for the kinds with no curve: a duration fills the bar over that time, a distance grows it.
  function previewBar(el: HTMLElement, kind: string, value: unknown): void {
    el.getAnimations().forEach(a => a.cancel());
    if (kind === 'duration') {
      el.animate(
        [{ transform: 'scaleX(0)' }, { transform: 'scaleX(1)' }],
        { duration: parseMsLocal(String(value)), easing: 'linear', fill: 'forwards' },
      );
    } else if (kind === 'distance') {
      el.animate(
        [{ width: '4px' }, { width: String(value) }],
        { duration: 400, easing: 'ease-out', fill: 'forwards' },
      );
    }
  }

  // The classic easing graph: progress over time, with 0 and 1 marked. Click to run a dot along it.
  function buildCurvePreview(curve: Curve): SVGSVGElement {
    const NS = 'http://www.w3.org/2000/svg';
    const W = 112, H = 84, PAD = 8;
    const svg = document.createElementNS(NS, 'svg');
    svg.setAttribute('viewBox', `0 0 ${W} ${H}`);
    svg.setAttribute('width', String(W));
    svg.setAttribute('height', String(H));
    svg.setAttribute('class', 'lab-curve');
    svg.setAttribute('role', 'img');
    svg.setAttribute('aria-label', 'Motion curve. Click to preview.');

    for (const level of [0, 1]) {
      const y = toY(curve, level, H, PAD);
      const guide = document.createElementNS(NS, 'line');
      guide.setAttribute('x1', String(PAD));
      guide.setAttribute('x2', String(W - PAD));
      guide.setAttribute('y1', String(y));
      guide.setAttribute('y2', String(y));
      guide.setAttribute('class', 'lab-curve__guide');
      svg.appendChild(guide);
    }
    const path = document.createElementNS(NS, 'path');
    path.setAttribute('d', curvePath(curve, W, H, PAD));
    path.setAttribute('class', 'lab-curve__line');
    svg.appendChild(path);
    const dot = document.createElementNS(NS, 'circle');
    dot.setAttribute('r', '4');
    dot.setAttribute('class', 'lab-curve__dot');
    const place = (t: number): void => {
      dot.setAttribute('cx', String(toX(t, W, PAD)));
      dot.setAttribute('cy', String(toY(curve, curveYAt(curve, t), H, PAD)));
    };
    place(0);
    svg.appendChild(dot);

    let frame = 0;
    svg.addEventListener('click', () => {
      cancelAnimationFrame(frame);
      const length = Math.max(curve.durationMs, 300);
      const began = performance.now();
      const tick = (now: number): void => {
        const t = Math.min((now - began) / length, 1);
        place(t);
        if (t < 1) frame = requestAnimationFrame(tick);
      };
      frame = requestAnimationFrame(tick);
    });
    return svg;
  }

  // One table of a kind. Each row is just the token name and its preview; the rest is in the tooltip.
  function buildTable(kind: string): HTMLTableElement {
    const table = document.createElement('table');
    table.className = 'lab-tokens-table';
    const headerRow = table.createTHead().insertRow();
    for (const text of ['Preview', 'Token']) {
      const th = document.createElement('th');
      th.textContent = text;
      headerRow.appendChild(th);
    }
    const tbody = table.createTBody();
    for (const { key, value } of tokensOf(kind)) {
      const row = tbody.insertRow();
      row.className = 'lab-token-row';
      row.title = tooltipFor(key);

      const previewCell = row.insertCell();
      const curve = curveFor(kind, key, value);
      if (curve) {
        previewCell.appendChild(buildCurvePreview(curve));
      } else if (kind === 'duration' || kind === 'distance') {
        const bar = document.createElement('div');
        bar.className = 'lab-token-preview';
        bar.addEventListener('click', () => previewBar(bar, kind, value));
        previewCell.appendChild(bar);
      }

      const code = document.createElement('code');
      code.className = 'lab-token-name';
      code.textContent = key;
      row.insertCell().appendChild(code);

    }
    return table;
  }

  const wrapper = document.createElement('div');
  wrapper.className = 'lab-tokens-view';

  const subtabs = document.createElement('div');
  subtabs.className = 'lab-tokens-subtabs';
  const tokenSetting = document.createElement('div');
  tokenSetting.className = 'lab-token-setting';
  const tableContainer = document.createElement('div');
  tableContainer.className = 'lab-tokens-table-wrap';

  for (const kind of tokenKinds()) {
    const btn = document.createElement('button');
    btn.className = 'lab-tokens-subtab' + (kind === activeKind ? ' lab-tokens-subtab--active' : '');
    btn.textContent = kind.charAt(0).toUpperCase() + kind.slice(1);
    btn.addEventListener('click', () => {
      activeKind = kind;
      subtabs.querySelectorAll('.lab-tokens-subtab').forEach(b => b.classList.toggle('lab-tokens-subtab--active', b === btn));
      renderKind(kind);
    });
    subtabs.appendChild(btn);
  }

  // A setting that picks one token of the kind on its tab, from that kind's tokens only:
  //  - bounce (Motion only): the bounce every motion that names none plays with
  //  - delay: the default stagger between components on the page view
  const SETTINGS: Record<string, { label: string; id: string; tokens: string[]; get: () => string; set: (t: string) => void; hint: string }> = {
    bounce: {
      label: 'Global bounce', id: 'bounce-control', tokens: bounceTokens, get: () => globalBounce, set: setGlobalBounce,
      hint: 'Used by every motion that names no bounce of its own, under Motion.',
    },
    delay: {
      label: 'Default stagger', id: 'stagger-control', tokens: delayTokens, get: () => defaultStagger, set: setDefaultStagger,
      hint: 'The delay between components on the page view. A page can use another delay token, or none.',
    },
  };

  function renderSetting(kind: string): void {
    tokenSetting.replaceChildren();
    const setting = SETTINGS[kind];
    if (!setting) return;
    const label = document.createElement('label');
    label.className = 'lab-control-label';
    label.append(setting.label);
    const select = document.createElement('select');
    select.id = setting.id;
    select.className = 'lab-select';
    for (const key of setting.tokens) {
      const opt = document.createElement('option');
      opt.value = key;
      opt.textContent = key;
      select.appendChild(opt);
    }
    select.value = setting.get();
    select.addEventListener('change', () => {
      setting.set(select.value);
      renderKind(kind);
    });
    label.appendChild(select);
    const hint = document.createElement('span');
    hint.className = 'lab-token-setting__hint';
    hint.textContent = setting.hint;
    tokenSetting.append(label, hint);
  }

  function renderKind(kind: string): void {
    tableContainer.replaceChildren();
    renderSetting(kind);
    tableContainer.appendChild(buildTable(kind));
  }

  wrapper.append(subtabs, tokenSetting, tableContainer);
  renderKind(activeKind);
  main.appendChild(wrapper);
}

// ── Library view ───────────────────────────────────────────────────────────
// /?view=library[&status=…][&archived=1][&q=…]
// Every component as a scaled live preview. A card plays its version on hover or
// focus and links to the component view.

// Fallback layout width for a hand-built component (no Figma frame) that measures as 0 wide.
const LIBRARY_UNFRAMED_WIDTH = 640;

let libraryObserver: ResizeObserver | null = null;

function getComponentModules(): Record<string, ComponentModule> {
  const modules: Record<string, ComponentModule> = {};
  for (const [path, module] of Object.entries(motionModules)) {
    const name = path.match(/\/components\/([^/]+)\/motion\.ts$/)?.[1];
    if (name && module) modules[name] = module;
  }
  return modules;
}

// Scale the component to fit its preview box, centered.
function fitLibraryPreview(box: HTMLElement, scaler: HTMLElement, width: number, height: number): void {
  const scale = Math.min(box.clientWidth / width, box.clientHeight / height);
  const x = (box.clientWidth - width * scale) / 2;
  const y = (box.clientHeight - height * scale) / 2;
  scaler.style.transform = `translate(${x}px, ${y}px) scale(${scale})`;
}

function renderLibraryView(params: URLSearchParams): void {
  const main = document.getElementById('main-content')!;
  main.innerHTML = '';
  main.className = 'lab-main lab-main--library';

  const filter = libraryFilterFromParams(params);

  const toolbar = document.createElement('div');
  toolbar.className = 'lab-library__toolbar';
  const search = document.createElement('input');
  search.type = 'search';
  search.id = 'library-search';
  search.className = 'lab-input';
  search.placeholder = 'Search components';
  search.setAttribute('aria-label', 'Search components');
  search.value = filter.query ?? '';
  const count = document.createElement('span');
  count.className = 'lab-library__count';
  count.id = 'library-count';
  const grid = document.createElement('div');
  grid.className = 'lab-library__grid';
  grid.id = 'library-grid';

  toolbar.append(search, buildVersionFilterControls(filter, renderGrid), count);
  main.append(toolbar, grid);

  search.addEventListener('input', () => {
    const sp = new URLSearchParams(window.location.search);
    if (search.value) sp.set('q', search.value); else sp.delete('q');
    window.history.replaceState(null, '', `?${sp.toString()}`);
    renderGrid();
  });

  function renderGrid(): void {
    libraryObserver?.disconnect();
    libraryObserver = new ResizeObserver(entries => {
      for (const e of entries) (e.target as HTMLElement & { refit?: () => void }).refit?.();
    });
    grid.innerHTML = '';

    const entries = buildLibraryEntries(
      getComponentModules(),
      libraryFilterFromParams(new URLSearchParams(window.location.search)),
    );
    count.textContent = `${entries.length} component${entries.length === 1 ? '' : 's'}`;

    if (entries.length === 0) {
      const empty = document.createElement('p');
      empty.className = 'lab-library__empty';
      empty.textContent = 'No components match.';
      grid.appendChild(empty);
      return;
    }

    for (const entry of entries) {
      const meta = metaModules[`../components/${entry.name}/meta.json`];

      const card = document.createElement('a');
      card.className = 'lab-library-card';
      card.href = `?view=component&component=${entry.name}&version=${entry.previewVersion.id}`;
      card.dataset['component'] = entry.name;

      const preview = document.createElement('div') as HTMLElement & { refit?: () => void };
      preview.className = 'lab-library-card__preview';
      const scaler = document.createElement('div');
      scaler.className = 'lab-library-card__scaler';
      scaler.style.width = meta ? `${meta.frame.width}px` : 'max-content';
      scaler.innerHTML = getFramedMarkup(entry.name);
      preview.appendChild(scaler);

      const footer = document.createElement('div');
      footer.className = 'lab-library-card__footer';
      const name = document.createElement('span');
      name.className = 'lab-library-card__name';
      name.textContent = entry.name;
      const versions = document.createElement('span');
      versions.className = 'lab-library-card__versions';
      versions.textContent = `${entry.totalVersions} version${entry.totalVersions === 1 ? '' : 's'}`;
      footer.append(name, statusBadge(entry.previewVersion), versions);

      card.append(preview, footer);
      grid.appendChild(card);

      // Figma frames know their size; hand-built components are measured once the card is in the DOM.
      const width = meta ? meta.frame.width : scaler.offsetWidth || LIBRARY_UNFRAMED_WIDTH;
      const height = meta ? meta.frame.height : scaler.offsetHeight;
      preview.refit = () => fitLibraryPreview(preview, scaler, width, height || 1);
      libraryObserver.observe(preview);

      const target =
        scaler.querySelector<HTMLElement>('[data-motion-target]') ??
        (scaler.firstElementChild as HTMLElement | null);
      if (target) {
        const play = (): void => {
          animateElement(target, entry.previewVersion);
        };
        card.addEventListener('pointerenter', play);
        card.addEventListener('focus', play);
      }
    }
  }

  renderGrid();
}

// ── Router ─────────────────────────────────────────────────────────────────

function route(): void {
  const params = new URLSearchParams(window.location.search);
  const view = params.get('view') ?? 'component';

  navBtns.forEach(btn => {
    const isActive = btn.dataset['view'] === view;
    btn.setAttribute('aria-pressed', String(isActive));
    btn.classList.toggle('lab-nav__btn--active', isActive);
  });

  if (view === 'frame') {
    renderFrameView(params);
  } else if (view === 'page') {
    renderPageView(params);
  } else if (view === 'tokens') {
    renderTokensView();
  } else if (view === 'library') {
    renderLibraryView(params);
  } else {
    renderComponentView(params);
  }
}

route();
