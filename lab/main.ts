function readBounce(): string {
  const fromUrl = new URLSearchParams(window.location.search).get('bounce');
  const valid = (k: string | null | undefined): k is string => !!k && bounceTokens.includes(k);
  if (fromUrl !== null) {
    const chosen = valid(`bounce.${fromUrl}`) ? `bounce.${fromUrl}` : DEFAULT_BOUNCE;
    try { sessionStorage.setItem(BOUNCE_KEY, chosen); } catch { /* storage can be blocked */ }
    return chosen;
  }
  try {
    const saved = sessionStorage.getItem(BOUNCE_KEY);
    return valid(saved) ? saved : DEFAULT_BOUNCE;
  } catch {
    return DEFAULT_BOUNCE;
  }
}

function readRuntime(): Runtime {
  const fromUrl = new URLSearchParams(window.location.search).get('runtime');
  if (fromUrl !== null) {
    const chosen = runtimeFromParam(fromUrl);
    try { sessionStorage.setItem(RUNTIME_KEY, chosen); } catch { /* storage can be blocked */ }
    return chosen;
  }
  try {
    return runtimeFromParam(sessionStorage.getItem(RUNTIME_KEY));
  } catch {
    return 'css';
  }
}

