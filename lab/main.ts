function getMarkup(componentName: string): string {
  const key = `../components/${componentName}/markup.html`;
  const markup = markupModules[key];
  if (!markup) return '<div class="lab-error">Component markup not found</div>';
  return markup.replace(/(src|href)="(assets\/[^"]+)"/g, (match, attr: string, path: string) => {
    const url = assetUrls[`../components/${componentName}/${path}`];
    return url ? `${attr}="${url}"` : match;
  });
}

// Imported components render at their Figma frame size: laid out at the design
// width, zoomed to the frame width (they differ when the Figma frame is a scaled instance).
function getFramedMarkup(componentName: string): string {
  const markup = getMarkup(componentName);
  const meta = metaModules[`../components/${componentName}/meta.json`];
  if (!meta) return markup;
  const zoom = meta.frame.width / meta.designWidth;
  return `<div class="lab-frame" style="width:${meta.designWidth}px;zoom:${zoom}">${markup}</div>`;
}

function getPageConfig(pageName: string): PageConfig | undefined {
  const key = `../pages/${pageName}/page.json`;
  return pageModules[key];
}

