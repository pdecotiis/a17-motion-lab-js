// One player per element and version, so the component view and the entrance share it.
const players = new WeakMap<HTMLElement, { versionId: string; runtime: Runtime; player: InteractionPlayer; detach: () => void }>();

function playerFor(el: HTMLElement, version: MotionVersion, onChange?: (state: string, transitioning: boolean) => void): InteractionPlayer {
  const known = players.get(el);
  if (known && known.versionId === version.id && known.runtime === runtime && !onChange) return known.player;
  known?.detach();
  const player = createInteractionPlayer(el, version, {
    raw, runtime, globalBounce,
    reducedMotion: () => prefersReducedMotion(),
    reducedPolicy: getReducedMotionPolicy(version),
    playbackRate: () => playbackRate,
    onHandle: handle => activeAnimations.push(handle),
    ...(onChange ? { onChange } : {}),
  });
  // The version's triggers (hover, press, focus, click) are live on the element wherever it is shown.
  players.set(el, { versionId: version.id, runtime, player, detach: player.attachTriggers() });
  return player;
}

// What an interaction version plays when something just asks it to play (a replay, a page, a library
// card): back to its resting state, then to the first other state. A version that is hovered, pressed or
// focused (its states last only while that does) goes back to rest after a moment, as if the pointer had
// left; one that is clicked (open, closed) stays where it went.
const DEMO_HOLD_MS = 700;

// A version that rests first (`interaction.hold`) waits before its first move; a replay cancels a wait still running.
const pendingStarts = new WeakMap<HTMLElement, number>();

function playInteractionEntrance(el: HTMLElement, version: MotionVersion): PlayHandle {
  const player = playerFor(el, version);
  window.clearTimeout(pendingStarts.get(el));
  // Reset first, and move on once it has taken effect (Motion applies it on its next frame).
  void player.reset().then(() => {
    const next = player.states().find(s => s !== player.state());
    if (!next) return;
    const hold = version.interaction?.hold;
    if (hold) {
      const rested = player.state();
      const ms = parseMsLocal(String(hold in raw ? raw[hold] : hold));
      pendingStarts.set(el, window.setTimeout(() => { if (player.state() === rested) player.goTo(next); }, ms / playbackRate));
      return;
    }
    player.goTo(next);
    if (version.interaction && hasHoldTriggers(version.interaction)) {
      window.setTimeout(() => { if (player.state() === next) player.goTo(version.interaction!.initial); }, DEMO_HOLD_MS / playbackRate);
    }
  });
  return cssHandle(el, el.animate([{}], { duration: 0, fill: 'both' }));
}

// Where an interaction version starts when the view opens: at rest, so it can be hovered or clicked, unless
// it has nothing a person would hover (an open/close), when it plays its first move so there is something to see.
function startInteraction(el: HTMLElement, version: MotionVersion): void {
  // A version that also appears plays its entrance, then rests with its states live.
  if (hasEntrance(version)) animateElement(el, version);
  else if (version.interaction && hasHoldTriggers(version.interaction)) void playerFor(el, version).reset();
  else playInteractionEntrance(el, version);
}

// The entrance of a version: its root motion and each layer's, cancelling what was playing on the element.
// Returns every handle, the root's first.
function playEntrance(el: HTMLElement, version: MotionVersion, staggerIndex: number): PlayHandle[] {
  el.getAnimations({ subtree: true }).forEach(a => a.cancel());
  activeAnimations.filter(h => el.contains(h.target)).forEach(h => h.cancel());
  activeAnimations = activeAnimations.filter(h => !h.finished && !el.contains(h.target));

  // Each motion on its element: the root, then each layer's elements. A preset is up to two motions on the
  // same element (its fade and its move); a layer with a stagger starts each of its elements a little after the one before.
  const handles: PlayHandle[] = [];
  for (const entry of stepsOf(version)) {
    const els = entry.name === null ? [el] : [...el.querySelectorAll<HTMLElement>(`[data-motion="${entry.name}"]`)];
    const gap = entry.elementStagger ? parseMsLocal(String(entry.elementStagger in raw ? raw[entry.elementStagger] : entry.elementStagger)) : 0;
    els.forEach((target, i) => handles.push(playStep(target, entry.version, staggerIndex, gap * i)));
  }
  activeAnimations.push(...handles);
  return handles;
}

// A version with an entrance and states (appears, then hovers and presses): the states are locked while
// the entrance plays; when it ends, the component is left at its resting state (where the entrance ended,
// so nothing jumps) and the triggers go live. Replaying starts again from the entrance's first frame.
const entranceRuns = new WeakMap<HTMLElement, number>();

function playEntranceThenStates(el: HTMLElement, version: MotionVersion, staggerIndex: number): PlayHandle {
  const run = (entranceRuns.get(el) ?? 0) + 1;
  entranceRuns.set(el, run);
  const player = playerFor(el, version);
  window.clearTimeout(pendingStarts.get(el));
  player.setLocked(true);
  void player.reset().then(() => {
    if (entranceRuns.get(el) !== run) return;
    const handles = playEntrance(el, version, staggerIndex);
    void Promise.all(handles.map(h => h.done ?? Promise.resolve())).then(async () => {
      if (entranceRuns.get(el) !== run) return;
      // Under CSS the entrance's animations hold their last frame; let go of them so the states can move it.
      if (runtime === 'css') el.getAnimations({ subtree: true }).forEach(a => a.cancel());
      await player.reset();
      if (entranceRuns.get(el) === run) player.setLocked(false);
      // An interaction with a hold then rests in its first state for that long and plays its first move (the entrance is the way in).
      const hold = version.interaction?.hold;
      const rested = player.state();
      const next = player.states().find(s => s !== rested);
      if (hold && next && entranceRuns.get(el) === run) {
        const ms = parseMsLocal(String(hold in raw ? raw[hold] : hold));
        pendingStarts.set(el, window.setTimeout(() => { if (entranceRuns.get(el) === run && player.state() === rested) player.goTo(next); }, ms / playbackRate));
      }
    });
  });
  return cssHandle(el, el.animate([{}], { duration: 0, fill: 'both' }));
}

function animateElement(el: HTMLElement, version: MotionVersion, staggerIndex = 0): PlayHandle {
  if (version.interaction && hasEntrance(version)) return playEntranceThenStates(el, version, staggerIndex);
  if (version.interaction) return playInteractionEntrance(el, version);
  return playEntrance(el, version, staggerIndex)[0]!;
}

// One motion on one element, played by the current runtime. The speed control sets the runtime's own
// speed, so durations and delays here are at normal speed.
function playStep(el: HTMLElement, version: MotionVersion, staggerIndex: number, extraDelayMs = 0): PlayHandle {
  const isReduced = prefersReducedMotion();
  // A stagger is a delay token (delay.80) or a literal (80ms).
  const staggerMs = version.stagger ? parseFloat(String(version.stagger in raw ? raw[version.stagger] : version.stagger)) : 0;
  const staggerDelay = staggerMs * staggerIndex + extraDelayMs;

  // reducedMotion: 'none' means no animation at all: the element shows its end state.
  // A motion with no opacity change (a preset's move track) has nothing to fade: it does not play, so it
  // cannot cover another motion's fade on the same element.
  if (isReduced && (getReducedMotionPolicy(version) === 'none' || !playbackOf(version, raw).keyframes.some(k => 'opacity' in k))) {
    return cssHandle(el, el.animate([{}], { duration: 0, fill: 'both' }));
  }

  if (runtime === 'motion') {
    const { keyframes, options } = motionArgsOf(version, raw, { reducedMotion: isReduced, extraDelayMs: staggerDelay, globalBounce });
    const controls = motionAnimate(el, keyframes, options);
    controls.speed = playbackRate;
    return {
      target: el,
      get speed() { return controls.speed; },
      set speed(v: number) { controls.speed = v; },
      get time() { return controls.time; },
      set time(v: number) { controls.time = v; },
      get finished() { return controls.state === 'finished'; },
      done: Promise.resolve(controls).then(() => undefined, () => undefined),
      cancel() { controls.cancel(); },
    };
  }

  const p = playbackOf(version, raw, { reducedMotion: isReduced });
  const anim = el.animate(p.keyframes, {
    duration: p.duration,
    easing: p.easing,
    delay: p.delay + staggerDelay,
    fill: 'both',
  });
  anim.playbackRate = playbackRate;
  return cssHandle(el, anim);
}

