// ── Helpers ────────────────────────────────────────────────────────────────

function parseMsLocal(value: string): number {
  if (value.endsWith('ms')) return parseFloat(value);
  if (value.endsWith('s')) return parseFloat(value) * 1000;
  return parseFloat(value);
}

function resolveInitialTiming(version: MotionVersion): { duration: number; delay: number; easing: string } {
  if (version.model.model === 'tween') {
    const t = resolveTiming(version, raw, {}, 1);
    return { duration: t.duration, delay: t.delay, easing: t.easing };
  }
  const r = buildSpringWaapiKeyframes(version, raw, { playbackRate: 1 });
  return { duration: r.duration, delay: r.delay, easing: r.easing ?? 'linear' };
}

// ── Animation helpers ──────────────────────────────────────────────────────

function animateElement(
  el: HTMLElement,
  version: MotionVersion,
  controls: LiveControls = {},
  staggerIndex = 0,
): Animation {
  el.getAnimations().forEach(a => a.cancel());

  const isReduced = prefersReducedMotion();
  const staggerMs = version.stagger ? parseFloat(version.stagger) : 0;
  const staggerDelay = (staggerMs * staggerIndex) / playbackRate;

  if (version.model.model === 'spring') {
    const builder = engineMode === 'spring' ? buildSpringWaapiKeyframes : buildSpringCssKeyframes;
    const { keyframes, duration, delay, easing } = builder(version, raw, {
      controls,
      playbackRate,
      reducedMotion: isReduced,
    });
    const anim = el.animate(keyframes, {
      duration,
      easing: easing ?? 'linear',
      delay: delay + staggerDelay,
      fill: 'both',
    });
    anim.playbackRate = playbackRate;
    return anim;
  }

  // Tween: WAAPI with cubic-bezier easing from tokens.
  const timing = resolveTiming(version, raw, controls, playbackRate);
  const effectiveDuration = getEffectiveDuration(timing.duration);
  const effectiveKeyframes = getEffectiveKeyframes(version.keyframes ?? [], isReduced);
  const options = buildAnimationOptions({
    ...timing,
    duration: effectiveDuration,
    delay: timing.delay + staggerDelay,
  });
  const anim = el.animate(effectiveKeyframes, options);
  anim.playbackRate = playbackRate;
  return anim;
}

