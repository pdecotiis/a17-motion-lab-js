/**
 * Figma import — the deterministic, file-writing half of the import workflow.
 *
 * The Figma MCP (design context, variables, screenshot, assets) is driven by the
 * agent; it hands the results to `importComponent` as an ImportInput. This module
 * writes the component folder, merges Figma variables into tokens/visual.css, and
 * scaffolds v1 only on first import. Re-imports never touch motion.ts or versions/.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, basename, extname } from 'node:path';

export interface ImportInput {
  /** kebab-case component name, derived from the Figma layer name */
  name: string;
  /** Figma link used for the import (kept for re-import) */
  figmaUrl: string;
  /** Figma layer name the component was named from */
  layerName: string;
  markup: string;
  styles: string;
  /** asset filename (written to components/<name>/assets/) → source file path */
  assets: Record<string, string>;
  /** Figma variables, name → value as returned by get_variable_defs (e.g. "space/3": "12") */
  variables: Record<string, string>;
  /** Size of the linked Figma frame, used by the frame view and the visual check */
  frame: { width: number; height: number };
  /** Native width of the design; when it differs from frame.width the frame is a scaled instance */
  designWidth?: number;
  /** ISO date; defaults to today */
  importedAt?: string;
  /** Figma file issues for designers (no auto layout, unnamed layers, …) */
  issues?: string[];
}

export interface ComponentMeta {
  name: string;
  layerName: string;
  figma: { url: string; fileKey: string; nodeId: string };
  importedAt: string;
  frame: { width: number; height: number };
  designWidth: number;
  variables: string[];
  assets: string[];
  fontFallbacks: string[];
  issues: string[];
}

export interface ImportResult {
  componentDir: string;
  scaffoldedVersion: boolean;
  fontFallbacks: string[];
}

// ── Naming ─────────────────────────────────────────────────────────────────

export function toKebab(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase();
}

export function parseFigmaUrl(url: string): { fileKey: string; nodeId: string } {
  const u = new URL(url);
  const parts = u.pathname.split('/').filter(Boolean);
  const branchIdx = parts.indexOf('branch');
  const fileKey = branchIdx >= 0 ? parts[branchIdx + 1] : parts[1];
  const nodeId = u.searchParams.get('node-id')?.replace('-', ':');
  if (!fileKey || !nodeId) throw new Error(`Figma URL needs a file key and node-id: ${url}`);
  return { fileKey, nodeId };
}

// ── Variables → CSS custom properties ──────────────────────────────────────

const FONT_WEIGHTS: Record<string, number> = {
  thin: 100, hairline: 100, ultralight: 200, extralight: 200, light: 300,
  regular: 400, normal: 400, book: 400, medium: 500, semibold: 600,
  bold: 700, extrabold: 800, black: 900,
};

const SANS_FALLBACK = '"Helvetica Neue", Helvetica, Arial, sans-serif';
const MONO_FALLBACK = 'ui-monospace, "SF Mono", Menlo, monospace';

export function cssVarName(figmaName: string): string {
  return `--${figmaName.split('/').map(toKebab).join('-')}`;
}

export function cssVarValue(figmaName: string, value: string): string {
  const leaf = figmaName.split('/').pop() ?? '';
  if (leaf === 'family') {
    return `"${value}", ${/mono/i.test(value) ? MONO_FALLBACK : SANS_FALLBACK}`;
  }
  if (leaf === 'weight') {
    return String(FONT_WEIGHTS[value.toLowerCase().replace(/\s+/g, '')] ?? value);
  }
  // Plain numbers are px, except counts.
  if (/^-?\d+(\.\d+)?$/.test(value)) {
    return /columns|count|opacity/.test(figmaName) ? value : `${value}px`;
  }
  return value;
}

export function buildVisualCss(variables: Record<string, string>): string {
  const names = Object.keys(variables).sort();
  const lines = names.map(n => `  ${cssVarName(n)}: ${cssVarValue(n, variables[n]!)};`);
  return [
    '/* Generated by scripts/figma-import from tokens/figma-variables.json. Do not edit by hand. */',
    ':root {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

// ── Fonts ──────────────────────────────────────────────────────────────────

function squash(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]/g, '');
}

/** Font families (with weight) referenced by Figma variables, e.g. ["Acme Sans Regular"]. */
export function fontFacesFromVariables(variables: Record<string, string>): { family: string; weight: string }[] {
  const faces = new Map<string, { family: string; weight: string }>();
  for (const [name, value] of Object.entries(variables)) {
    if (!name.endsWith('/family')) continue;
    const weight = variables[name.replace(/family$/, 'weight')] ?? 'Regular';
    faces.set(`${value}|${weight}`, { family: value, weight });
  }
  return [...faces.values()];
}

/**
 * Builds tokens/fonts.css from files in /fonts that match the Figma typefaces.
 * Returns the faces with no matching file (they use the system fallback in visual.css).
 */
export function buildFontsCss(root: string, variables: Record<string, string>): { css: string; missing: string[] } {
  const fontsDir = join(root, 'fonts');
  const files = existsSync(fontsDir) ? readdirSync(fontsDir).filter(f => /\.(woff2?|otf|ttf)$/i.test(f)) : [];
  const rules: string[] = [];
  const missing: string[] = [];
  for (const { family, weight } of fontFacesFromVariables(variables)) {
    const want = squash(family + weight);
    const file = files.find(f => squash(basename(f, extname(f))) === want);
    if (!file) { missing.push(`${family} ${weight}`); continue; }
    rules.push(
      `@font-face {\n  font-family: "${family}";\n  font-weight: ${cssVarValue('x/weight', weight)};\n` +
      `  font-style: normal;\n  font-display: swap;\n  src: url("../fonts/${file}");\n}`,
    );
  }
  const header = '/* Generated by scripts/figma-import from files in /fonts (gitignored). Do not edit by hand. */';
  return { css: [header, ...rules, ''].join('\n'), missing };
}

// ── Version scaffold (first import only) ───────────────────────────────────

export function scaffoldV1(figmaUrl: string): string {
  return `import type { MotionVersion } from '../../../lab/lib/types.js';

// Default entrance scaffolded by the Figma import. Edit freely: re-imports never touch this file.
export const v1: MotionVersion = {
  id: 'v1',
  label: 'Default Entrance',
  model: {
    model: 'tween',
    duration: 'motion.timings.slow',
    easing: 'motion.easings.ease-out',
    delay: '0ms',
  },
  keyframes: [
    { opacity: 0, transform: 'translateY(16px)', offset: 0 }, // motion.distances.md
    { opacity: 1, transform: 'translateY(0px)', offset: 1 },
  ],
  status: 'in-progress',
  lineage: ${JSON.stringify(`imported from ${figmaUrl}`)},
};

export default v1;
`;
}

export function scaffoldMotionIndex(): string {
  return `import type { MotionVersion, ComponentModule } from '../../lab/lib/types.js';
import { v1 } from './versions/v1.js';

// One file per version in ./versions/. Add new versions there and list them here.
export { v1 };
export const versions: MotionVersion[] = [v1];
export const defaultVersion = 'v1';

const module: ComponentModule = { versions, defaultVersion };
export default module;
`;
}

// ── Import ─────────────────────────────────────────────────────────────────

const VARIABLES_FILE = 'tokens/figma-variables.json';

function readJson<T>(path: string, fallback: T): T {
  return existsSync(path) ? (JSON.parse(readFileSync(path, 'utf8')) as T) : fallback;
}

/**
 * Writes (or re-writes) components/<name>/ from a Figma import.
 * Updates: markup.html, styles.css, assets/, meta.json, tokens/visual.css, tokens/fonts.css.
 * Creates only if absent: motion.ts, versions/v1.ts. Never modifies existing version files.
 */
export function importComponent(root: string, input: ImportInput): ImportResult {
  if (input.name !== toKebab(input.name)) throw new Error(`Component name must be kebab-case: "${input.name}"`);
  const dir = join(root, 'components', input.name);
  mkdirSync(dir, { recursive: true });

  writeFileSync(join(dir, 'markup.html'), input.markup.trimEnd() + '\n');
  writeFileSync(join(dir, 'styles.css'), input.styles.trimEnd() + '\n');

  // Assets: read every source first (sources may live in the folder being replaced).
  const assetBuffers = Object.entries(input.assets).map(([file, src]) => [file, readFileSync(src)] as const);
  const assetsDir = join(dir, 'assets');
  rmSync(assetsDir, { recursive: true, force: true });
  if (assetBuffers.length > 0) {
    mkdirSync(assetsDir, { recursive: true });
    for (const [file, buf] of assetBuffers) writeFileSync(join(assetsDir, file), buf);
  }

  // Variables: merge into the project-wide map, regenerate visual.css and fonts.css.
  const varsPath = join(root, VARIABLES_FILE);
  const allVars = { ...readJson<Record<string, string>>(varsPath, {}), ...input.variables };
  mkdirSync(join(root, 'tokens'), { recursive: true });
  writeFileSync(varsPath, JSON.stringify(allVars, Object.keys(allVars).sort(), 2) + '\n');
  writeFileSync(join(root, 'tokens/visual.css'), buildVisualCss(allVars));
  const fonts = buildFontsCss(root, allVars);
  writeFileSync(join(root, 'tokens/fonts.css'), fonts.css);
  const ownFaces = fontFacesFromVariables(input.variables).map(f => `${f.family} ${f.weight}`);
  const fontFallbacks = fonts.missing.filter(f => ownFaces.includes(f));

  const meta: ComponentMeta = {
    name: input.name,
    layerName: input.layerName,
    figma: { url: input.figmaUrl, ...parseFigmaUrl(input.figmaUrl) },
    importedAt: input.importedAt ?? new Date().toISOString().slice(0, 10),
    frame: input.frame,
    designWidth: input.designWidth ?? input.frame.width,
    variables: Object.keys(input.variables).sort(),
    assets: Object.keys(input.assets).sort(),
    fontFallbacks,
    issues: input.issues ?? [],
  };
  writeFileSync(join(dir, 'meta.json'), JSON.stringify(meta, null, 2) + '\n');

  // Versions: scaffold on first import only.
  const motionPath = join(dir, 'motion.ts');
  const versionsDir = join(dir, 'versions');
  let scaffoldedVersion = false;
  if (!existsSync(motionPath) && !existsSync(versionsDir)) {
    mkdirSync(versionsDir, { recursive: true });
    writeFileSync(join(versionsDir, 'v1.ts'), scaffoldV1(input.figmaUrl));
    writeFileSync(motionPath, scaffoldMotionIndex());
    scaffoldedVersion = true;
  }

  return { componentDir: dir, scaffoldedVersion, fontFallbacks };
}

// ── Structural validation ──────────────────────────────────────────────────

/** Returns a list of problems with an imported component folder (empty = valid). */
export function validateImportedComponent(root: string, name: string): string[] {
  const dir = join(root, 'components', name);
  const errors: string[] = [];
  for (const f of ['markup.html', 'styles.css', 'motion.ts', 'meta.json', 'versions/v1.ts']) {
    if (!existsSync(join(dir, f))) errors.push(`missing ${f}`);
  }
  if (errors.length) return errors;

  const meta = JSON.parse(readFileSync(join(dir, 'meta.json'), 'utf8')) as Partial<ComponentMeta>;
  if (meta.name !== name) errors.push('meta.json name does not match folder');
  if (!meta.figma?.url?.startsWith('https://www.figma.com/')) errors.push('meta.json missing figma.url');
  if (!meta.importedAt || Number.isNaN(Date.parse(meta.importedAt))) errors.push('meta.json missing importedAt');
  if (!meta.frame?.width || !meta.frame?.height) errors.push('meta.json missing frame size');

  const markup = readFileSync(join(dir, 'markup.html'), 'utf8');
  const styles = readFileSync(join(dir, 'styles.css'), 'utf8');
  if (!/data-motion-target/.test(markup)) errors.push('markup.html has no data-motion-target');
  if (!/data-motion="[a-z0-9-]+"/.test(markup)) errors.push('markup.html has no data-motion="<layer-name>" attributes');

  const refs = [
    ...[...markup.matchAll(/(?:src|href)="(assets\/[^"]+)"/g)].map(m => m[1]!),
    ...[...styles.matchAll(/url\(["']?\.?\/?(assets\/[^"')]+)["']?\)/g)].map(m => m[1]!),
  ];
  for (const ref of refs) {
    if (!existsSync(join(dir, ref))) errors.push(`asset not found: ${ref}`);
  }
  if (/figma\.com\/api\/mcp\/asset/.test(markup + styles)) errors.push('temporary Figma asset URL left in source');

  const versionNum = (f: string) => parseInt(f.replace(/\D/g, ''), 10);
  const versionFiles = readdirSync(join(dir, 'versions')).filter(f => f.endsWith('.ts'))
    .sort((a, b) => versionNum(a) - versionNum(b));
  versionFiles.forEach((f, i) => {
    if (f !== `v${i + 1}.ts`) errors.push(`version files must be v1.ts, v2.ts, … without gaps (found ${f})`);
  });
  return errors;
}
